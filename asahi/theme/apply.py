def install_ghostty_theme(theme_file: Path) -> Path | None:
    candidates = [
        Path.home() / ".config" / "ghostty" / "themes",
        Path.home() / ".dotfiles" / "asahi" / "ghostty" / "themes",
    ]
    for themes in candidates:
        if themes.parent.exists() or themes.exists():
            themes.mkdir(parents=True, exist_ok=True)
            dest = themes / "asahi-adaptive"
            shutil.copy2(theme_file, dest)
            return dest
    return None


def install_librewolf_css(css_file: Path) -> list[Path]:
    roots = [
        Path.home() / ".config" / "librewolf" / "librewolf",
        Path.home() / ".librewolf",
    ]
    written: list[Path] = []
    for root in roots:
        if not root.is_dir():
            continue
        for profile in root.glob("*.default*"):
            chrome = profile / "chrome"
            chrome.mkdir(parents=True, exist_ok=True)
            dest = chrome / "asahi-adaptive.css"
            shutil.copy2(css_file, dest)
            written.append(dest)
    return written


def apply_hyprland_live(p: Palette) -> None:
    if not shutil.which("hyprctl"):
        return
    active = _hex_rgb(p.accent)
    secondary = _hex_rgb(p.mauve)
    inactive = _hex_rgb(p.surface1)
    text = _hex_rgb(p.text)
    muted = _hex_rgb(p.subtext0)
    base = _hex_rgb(p.base)
    # hyprctl keyword is rejected by the lua provider; eval applies borders live.
    lua = (
        "hl.config({ general = { "
        f'["col.active_border"] = {{ colors = {{ "rgb({active})", "rgb({secondary})" }}, angle = 45 }}, '
        f'["col.inactive_border"] = "rgb({inactive})" '
        "}, group = { "
        f'["col.border_active"] = {{ colors = {{ "rgb({active})", "rgb({secondary})" }}, angle = 45 }}, '
        f'["col.border_inactive"] = "rgb({inactive})", '
        "groupbar = { "
        f'text_color = "rgb({text})", '
        f'text_color_inactive = "rgba({muted}90)", '
        f'col = {{ active = "rgba({base}dd)", inactive = "rgba({base}88)" }} '
        "} } })"
    )
    subprocess.run(["hyprctl", "eval", lua], check=False, capture_output=True)


def install_gtk_css(css_file: Path) -> list[Path]:
    written: list[Path] = []
    import_line = '@import url("asahi-adaptive.css");\n'
    for ver in ("gtk-3.0", "gtk-4.0"):
        dest_dir = Path.home() / ".config" / ver
        dest_dir.mkdir(parents=True, exist_ok=True)
        dest = dest_dir / "asahi-adaptive.css"
        shutil.copy2(css_file, dest)
        written.append(dest)
        gtk_css = dest_dir / "gtk.css"
        if gtk_css.is_symlink():
            gtk_css.unlink()
        existing = gtk_css.read_text(encoding="utf-8") if gtk_css.is_file() else ""
        if "asahi-adaptive.css" not in existing:
            _atomic_write(gtk_css, import_line + existing)
    return written


def install_chromium_policy(policy_file: Path) -> list[Path]:
    written: list[Path] = []
    roots = [
        Path.home() / ".config" / "chromium" / "policies" / "managed",
        Path.home() / ".config" / "chromium-browser" / "policies" / "managed",
    ]
    for root in roots:
        # Prefer chromium; only create chromium-browser policy if that tree exists.
        parent = root.parent.parent
        if not parent.is_dir() and "chromium-browser" in str(root):
            continue
        root.mkdir(parents=True, exist_ok=True)
        dest = root / "asahi-theme.json"
        shutil.copy2(policy_file, dest)
        written.append(dest)
    return written


def apply_chromium_live() -> None:
    binary = shutil.which("chromium-browser") or shutil.which("chromium")
    if not binary:
        return
    running = subprocess.run(
        ["pgrep", "-x", "chromium"], check=False, capture_output=True
    )
    if running.returncode != 0:
        running = subprocess.run(
            ["pgrep", "-x", "chromium-browser"], check=False, capture_output=True
        )
    if running.returncode != 0:
        return
    subprocess.run(
        [binary, "--refresh-platform-policy", "--no-startup-window"],
        check=False,
        capture_output=True,
    )


def apply_gsettings(p: Palette) -> None:
    if not shutil.which("gsettings"):
        return
    scheme = "prefer-dark" if p.mode == "dark" else "prefer-light"
    gtk = "adw-gtk3-dark" if p.mode == "dark" else "adw-gtk3"
    icons = "Papirus-Dark" if p.mode == "dark" else "Papirus"
    subprocess.run(
        ["gsettings", "set", "org.gnome.desktop.interface", "color-scheme", scheme],
        check=False,
        capture_output=True,
    )
    subprocess.run(
        ["gsettings", "set", "org.gnome.desktop.interface", "gtk-theme", gtk],
        check=False,
        capture_output=True,
    )
    subprocess.run(
        ["gsettings", "set", "org.gnome.desktop.interface", "icon-theme", icons],
        check=False,
        capture_output=True,
    )


def reload_ghostty() -> None:
    if not shutil.which("gdbus"):
        return
    subprocess.run(
        [
            "gdbus",
            "call",
            "--session",
            "--dest",
            "com.mitchellh.ghostty",
            "--object-path",
            "/com/mitchellh/ghostty",
            "--method",
            "org.gtk.Actions.Activate",
            "reload-config",
            "[]",
            "{}",
        ],
        check=False,
        capture_output=True,
    )


