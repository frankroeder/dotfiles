def install_btop_theme(theme_file: Path) -> Path | None:
    themes = Path.home() / ".config" / "btop" / "themes"
    if not themes.parent.is_dir():
        return None
    dest = themes / "asahi-adaptive.theme"
    _atomic_write(dest, theme_file.read_bytes())
    return dest


def reload_btop() -> None:
    # btop re-reads its theme on SIGUSR2; no-op when nothing is running.
    subprocess.run(["pkill", "-SIGUSR2", "-x", "btop"], check=False, capture_output=True)


def install_ghostty_theme(theme_file: Path, themes: Path | None = None) -> Path | None:
    candidates = [themes] if themes is not None else [
        Path.home() / ".config" / "ghostty" / "themes",
        Path.home() / ".dotfiles" / "asahi" / "ghostty" / "themes",
    ]
    for dest_dir in candidates:
        if dest_dir is None:
            continue
        if dest_dir.parent.exists() or dest_dir.exists():
            dest = dest_dir / "asahi-adaptive"
            _atomic_write(dest, theme_file.read_bytes())
            return dest
    return None


def apply_hyprland_live(p: Palette) -> None:
    if not shutil.which("hyprctl"):
        return
    # hyprctl keyword is rejected by the lua provider; eval applies borders live (as one line).
    subprocess.run(["hyprctl", "eval", _hyprland_lua(p).replace("\n", " ")], check=False, capture_output=True)


def install_gtk_css(css_file: Path) -> list[Path]:
    written: list[Path] = []
    import_line = '@import url("asahi-adaptive.css");\n'
    for ver in ("gtk-3.0", "gtk-4.0"):
        dest_dir = Path.home() / ".config" / ver
        dest_dir.mkdir(parents=True, exist_ok=True)
        dest = dest_dir / "asahi-adaptive.css"
        _atomic_write(dest, css_file.read_bytes())
        written.append(dest)
        gtk_css = dest_dir / "gtk.css"
        if gtk_css.is_symlink():
            gtk_css.unlink()
        existing = gtk_css.read_text(encoding="utf-8") if gtk_css.is_file() else ""
        if "asahi-adaptive.css" not in existing:
            _atomic_write(gtk_css, import_line + existing)
    return written


def reload_ghostty() -> None:
    if not shutil.which("gdbus"):
        return
    subprocess.run(
        [
            "gdbus",
            "call",
            "--session",
            "--dest",
            "com.mitchellh.ghostty",
            "--object-path",
            "/com/mitchellh/ghostty",
            "--method",
            "org.gtk.Actions.Activate",
            "reload-config",
            "[]",
            "{}",
        ],
        check=False,
        capture_output=True,
    )


def ghostty_config_dir() -> Path:
    ghostty_cfg = Path.home() / ".config" / "ghostty"
    if not ghostty_cfg.exists():
        ghostty_cfg = Path.home() / ".dotfiles" / "asahi" / "ghostty"
    return ghostty_cfg


def preview_ghostty(
    p: Palette,
    *,
    ghostty_cfg: Path | None = None,
    theme_state: Path | None = None,
    reload: bool = True,
) -> dict[str, Path | None]:
    """Retheme Ghostty only: the files it actually reads, then reload-config.

    Carousel `--preview` used to write `state/ghostty.theme` and reload.
    Ghostty loads `theme = asahi-adaptive` plus `adaptive.css`, so that
    reload was a no-op on the terminal.
    """
    cfg = ghostty_cfg or ghostty_config_dir()
    theme_state = theme_state or (state_dir() / "ghostty.theme")
    write_ghostty_theme(p, theme_state)
    installed = install_ghostty_theme(theme_state, themes=cfg / "themes")
    css = cfg / "adaptive.css"
    extra = cfg / "adaptive.conf"
    cfg.mkdir(parents=True, exist_ok=True)
    write_ghostty_gtk_css(p, css)
    write_ghostty_extra(p, extra, css_name=css.name)
    if reload:
        reload_ghostty()
    return {
        "ghostty": theme_state,
        "ghostty_installed": installed,
        "ghostty_css": css,
        "ghostty_extra": extra,
    }


def write_colors_env(p: Palette, path: Path) -> None:
    content = f"""# Generated by asahi-autotheme
export CATPPUCCIN_TERM_MODE="{p.mode}"
export CATPPUCCIN_TERM_BACKGROUND="{p.background}"
export CATPPUCCIN_TERM_FOREGROUND="{p.foreground}"
export CATPPUCCIN_TERM_SELECTION_BG="{p.selection}"
export CATPPUCCIN_TERM_CURSOR="{p.accent}"
"""
    names = ["BLACK", "RED", "GREEN", "YELLOW", "BLUE", "MAGENTA", "CYAN", "WHITE"]
    names += ["BRIGHT_" + n for n in names]
    content += "".join(f'export CATPPUCCIN_TERM_{n}="{c}"\n' for n, c in zip(names, _term16(p)))
    _atomic_write(path, content)


def write_screensaver_toml(p: Palette, path: Path) -> None:
    content = (
        f'background = "{p.background}"\n'
        f'foreground = "{p.foreground}"\n'
        f'color1 = "{p.red}"\n'
        f'accent = "{p.accent}"\n'
    )
    _atomic_write(path, content)


def bump_theme_marker(path: Path, name: str = "wallpaper") -> None:
    import time

    _atomic_write(path, f"{name}-{int(time.time())}\n")


def apply_gtk_settings(p: Palette) -> None:
    # settings.ini for GTK apps at start, gsettings for the portal and running apps.
    dark = p.mode == "dark"
    gtk = "adw-gtk3-dark" if dark else "adw-gtk3"
    icons = "Papirus-Dark" if dark else "Papirus"
    body = (
        "[Settings]\n"
        f"gtk-application-prefer-dark-theme={int(dark)}\n"
        f"gtk-theme-name={gtk}\n"
        f"gtk-icon-theme-name={icons}\n"
        "gtk-cursor-theme-size=24\n"
    )
    for ver in ("gtk-3.0", "gtk-4.0"):
        path = Path.home() / ".config" / ver / "settings.ini"
        if path.is_symlink():
            path.unlink()
        _atomic_write(path, body)
    if shutil.which("gsettings"):
        scheme = "prefer-dark" if dark else "prefer-light"
        for key, value in (("color-scheme", scheme), ("gtk-theme", gtk), ("icon-theme", icons)):
            subprocess.run(["gsettings", "set", "org.gnome.desktop.interface", key, value], check=False, capture_output=True)


def write_all(p: Palette) -> dict[str, Path]:
    root = state_dir()
    ghostty_cfg = ghostty_config_dir()
    adaptive_conf = ghostty_cfg / "adaptive.conf"
    adaptive_css = ghostty_cfg / "adaptive.css"

    paths = {
        "colors_json": root / "colors.json",
        "ghostty": root / "ghostty.theme",
        "ghostty_extra": adaptive_conf,
        "ghostty_css": adaptive_css,
        "hyprland": root / "hyprland.lua",
        "hyprlock": root / "hyprlock.conf",
        "firefox": root / "firefox.json",
        "btop": root / "btop.theme",
        "gtk_css": root / "gtk.css",
        "wallpaper": root / "wallpaper",
        "screensaver": root / "screensaver-colors.toml",
        "theme_name": root / "theme.name",
        "colors_env": root / "colors.env",
    }
    write_colors_json(p, paths["colors_json"])
    write_colors_env(p, paths["colors_env"])
    write_ghostty_theme(p, paths["ghostty"])
    write_ghostty_gtk_css(p, paths["ghostty_css"])
    write_ghostty_extra(p, paths["ghostty_extra"], css_name=adaptive_css.name)
    write_hyprland_lua(p, paths["hyprland"])
    write_hyprlock_conf(p, paths["hyprlock"])
    write_firefox_scheme(p, paths["firefox"])
    write_btop_theme(p, paths["btop"])
    write_gtk_css(p, paths["gtk_css"])
    write_screensaver_toml(p, paths["screensaver"])
    _atomic_write(paths["wallpaper"], p.wallpaper + "\n")
    install_ghostty_theme(paths["ghostty"])
    install_btop_theme(paths["btop"])
    install_gtk_css(paths["gtk_css"])
    # Bump last so FileView watchers reload after all artifacts exist.
    bump_theme_marker(paths["theme_name"], Path(p.wallpaper).stem or "wallpaper")
    return paths


def apply_live(p: Palette) -> None:
    apply_gtk_settings(p)
    apply_hyprland_live(p)
    reload_ghostty()
    reload_btop()
