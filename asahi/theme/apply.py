def bump_theme_marker(path: Path, name: str = "wallpaper") -> None:
    import time

    _atomic_write(path, f"{name}-{int(time.time())}\n")


def apply_gtk_settings(p: Palette) -> None:
    prefer = "0" if p.mode == "light" else "1"
    gtk = "adw-gtk3" if p.mode == "light" else "adw-gtk3-dark"
    icons = "Papirus" if p.mode == "light" else "Papirus-Dark"
    body = (
        "[Settings]\n"
        f"gtk-application-prefer-dark-theme={prefer}\n"
        f"gtk-theme-name={gtk}\n"
        f"gtk-icon-theme-name={icons}\n"
        "gtk-cursor-theme-size=24\n"
    )
    for ver in ("gtk-3.0", "gtk-4.0"):
        path = Path.home() / ".config" / ver / "settings.ini"
        path.parent.mkdir(parents=True, exist_ok=True)
        if path.is_symlink():
            path.unlink()
        _atomic_write(path, body)


def write_all(p: Palette) -> dict[str, Path]:
    root = state_dir()
    ghostty_cfg = Path.home() / ".config" / "ghostty"
    # Prefer writing next to the live Ghostty config (Asahi symlink → repo).
    if not ghostty_cfg.exists():
        ghostty_cfg = Path.home() / ".dotfiles" / "asahi" / "ghostty"
    adaptive_conf = ghostty_cfg / "adaptive.conf"
    adaptive_css = ghostty_cfg / "adaptive.css"

    paths = {
        "colors_json": root / "colors.json",
        "colors_toml": root / "colors.toml",
        "ghostty": root / "ghostty.theme",
        "ghostty_extra": adaptive_conf,
        "ghostty_css": adaptive_css,
        "hyprland": root / "hyprland.lua",
        "hyprlock": root / "hyprlock.conf",
        "librewolf": root / "librewolf.css",
        "gtk_css": root / "gtk.css",
        "chromium": root / "chromium-theme.json",
        "wallpaper": root / "wallpaper",
        "screensaver": root / "screensaver-colors.toml",
        "theme_name": root / "theme.name",
        "colors_env": root / "colors.env",
    }
    write_colors_json(p, paths["colors_json"])
    write_colors_toml(p, paths["colors_toml"])
    write_colors_env(p, paths["colors_env"])
    write_ghostty_theme(p, paths["ghostty"])
    write_ghostty_gtk_css(p, paths["ghostty_css"])
    write_ghostty_extra(p, paths["ghostty_extra"], css_name=adaptive_css.name)
    write_hyprland_lua(p, paths["hyprland"])
    write_hyprlock_conf(p, paths["hyprlock"])
    write_librewolf_css(p, paths["librewolf"])
    write_gtk_css(p, paths["gtk_css"])
    write_chromium_policy(p, paths["chromium"])
    write_screensaver_toml(p, paths["screensaver"])
    _atomic_write(paths["wallpaper"], p.wallpaper + "\n")
    install_ghostty_theme(paths["ghostty"])
    install_librewolf_css(paths["librewolf"])
    install_gtk_css(paths["gtk_css"])
    install_chromium_policy(paths["chromium"])
    # Bump last so FileView watchers reload after all artifacts exist.
    bump_theme_marker(paths["theme_name"], Path(p.wallpaper).stem or "wallpaper")
    return paths


def apply_live(p: Palette) -> None:
    apply_gtk_settings(p)
    apply_hyprland_live(p)
    apply_gsettings(p)
    apply_chromium_live()
    reload_ghostty()
