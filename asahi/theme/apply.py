def _hyprland_lua(p: Palette) -> str:
    # Borders + groupbar: dofile()d at startup (general.lua) and eval'd live.
    active = _hex_rgb(p.accent)
    secondary = _hex_rgb(p.mauve)
    locked = _hex_rgb(p.yellow)
    locked2 = _hex_rgb(p.peach)
    inactive = _hex_rgb(p.surface1)
    text = _hex_rgb(p.text)
    muted = _hex_rgb(p.subtext0)
    base = _hex_rgb(p.base)
    return f"""hl.config({{
  general = {{
    ["col.active_border"] = {{ colors = {{ "rgb({active})", "rgb({secondary})" }}, angle = 45 }},
    ["col.inactive_border"] = "rgb({inactive})",
  }},
  group = {{
    ["col.border_active"] = {{ colors = {{ "rgb({active})", "rgb({secondary})" }}, angle = 45 }},
    ["col.border_inactive"] = "rgb({inactive})",
    ["col.border_locked_active"] = {{ colors = {{ "rgb({locked})", "rgb({locked2})" }}, angle = 45 }},
    ["col.border_locked_inactive"] = "rgb({inactive})",
    groupbar = {{
      text_color = "rgb({text})",
      text_color_inactive = "rgba({muted}90)",
      col = {{
        active = "rgba({base}dd)",
        inactive = "rgba({base}88)",
      }},
    }},
  }},
}})
"""


def write_hyprland_lua(p: Palette, path: Path) -> None:
    _atomic_write(path, "-- Generated by asahi-autotheme\n" + _hyprland_lua(p))


def write_fade_png(path: Path, rgb: str, height: int, peak: float, bottom: bool = False) -> None:
    """Edge fade in `rgb`: alpha `peak` over the 40% of rows at the edge (where the
    text sits), easing to 0 at the far end. Top edge, or bottom with `bottom`.
    4000 wide covers a 3840 panel."""
    r, g, b = (int(rgb[i:i + 2], 16) for i in (0, 2, 4))
    width = 4000
    rows = []
    for y in range(height):
        d = y if bottom else height - y   # rows from the far end
        a = round(255 * peak * min(1.0, d / (0.6 * height)) ** 2)
        rows.append(b"\x00" + bytes((r, g, b, a)) * width)

    def chunk(kind: bytes, data: bytes) -> bytes:
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data))

    ihdr = struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0)
    png = b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", ihdr) + chunk(b"IDAT", zlib.compress(b"".join(rows), 9)) + chunk(b"IEND", b"")
    _atomic_write(path, png)


def lock_accents(p: Palette) -> tuple[str, str]:
    """The lock screen's two accents: the wallpaper accent pushed toward the gamut edge at a lightness that reads
    on the glass (dark: at least 0.74, light: at most 0.55), and its +40° neighbour (gradients). A grey accent (mono
    flavour) stays grey."""
    h = p.accent.lstrip("#")
    lch = from_srgb8(*(int(h[i:i + 2], 16) for i in (0, 2, 4))).to_oklch()
    light = max(lch.L, 0.74) if p.mode == "dark" else min(lch.L, 0.55)
    chroma = lch.C * 1.6 if lch.C < 0.02 else max(lch.C * 1.35, 0.11)
    return tuple(hex_from_oklch(light, min(chroma, 0.92 * max_chroma(light, hue)), hue) for hue in (lch.H, lch.H + 40))


def write_lock_fades(p: Palette, root: Path) -> None:
    # The lock screen's (remix/lock.qml) top fade behind the hostname and bottom fade behind its row, in the scheme's
    # background. hyprlock's colour conf that came with them is gone (2026-11-22).
    bg = _hex_rgb(p.background)
    write_fade_png(root / "lock-fade-top.png", bg, 260, 0.6)
    write_fade_png(root / "lock-fade-bottom.png", bg, 620, 0.82, bottom=True)


