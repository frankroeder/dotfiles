def install_claude_theme(theme_file: Path) -> Path | None:
    # Claude Code hot-reloads ~/.claude/themes (omarchy's note); nothing when Claude Code is not set up here.
    cfg = Path(os.environ.get("CLAUDE_CONFIG_DIR") or Path.home() / ".claude")
    if not cfg.is_dir():
        return None
    dest = cfg / "themes" / "asahi.json"
    _atomic_write(dest, theme_file.read_bytes())
    return dest


