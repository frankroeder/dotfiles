"""Write theme artifacts and apply them live to the Asahi desktop stack."""

from __future__ import annotations

import json
import os
import shutil
import struct
import subprocess
import tempfile
import zlib
from pathlib import Path

from .palette import Palette

STATE_DIR_NAME = "asahi-theme"


def state_dir() -> Path:
    xdg = os.environ.get("XDG_STATE_HOME")
    base = Path(xdg) if xdg else Path.home() / ".local" / "state"
    path = base / STATE_DIR_NAME
    path.mkdir(parents=True, exist_ok=True)
    return path


def _atomic_write(path: Path, data: str | bytes) -> None:
    # Unique tmp beside the target, then rename: watchers never read a half-written file,
    # and two runs never share (and clobber) one tmp.
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.")
    with os.fdopen(fd, "wb") as f:
        f.write(data.encode("utf-8") if isinstance(data, str) else data)
    os.chmod(tmp, 0o644)   # mkstemp creates 0600
    os.replace(tmp, path)


def _hex_rgb(hx: str) -> str:
    return hx.lstrip("#")


def write_colors_json(p: Palette, path: Path) -> None:
    _atomic_write(path, json.dumps(p.to_dict(), indent=2, sort_keys=True) + "\n")


def _term16(p: Palette) -> list[str]:
    """ANSI colors 0..15 (Ghostty palette, colors.env). The greys follow Catppuccin:
    Mocha-like in dark mode, Latte-like (dark 0/8, light 7/15) in light mode."""
    if p.mode == "dark":
        black, white, bright_black, bright_white = p.surface1, p.subtext1, p.overlay0, p.bright_foreground
    else:
        black, white, bright_black, bright_white = p.subtext1, p.surface2, p.overlay2, p.surface1
    return [black, p.red, p.green, p.yellow, p.blue, p.magenta, p.cyan, white,
            bright_black, p.bright_red, p.bright_green, p.bright_yellow, p.bright_blue, p.bright_magenta, p.bright_cyan,
            bright_white]


def write_ghostty_theme(p: Palette, path: Path) -> None:
    content = f"""# Generated by asahi-autotheme from wallpaper
background = {p.background}
foreground = {p.foreground}
cursor-color = {p.accent}
cursor-text = {p.crust}
selection-background = {p.selection}
selection-foreground = {p.foreground}
"""
    content += "".join(f"palette = {i}={c}\n" for i, c in enumerate(_term16(p)))
    _atomic_write(path, content)


def _adwaita_colors(p: Palette) -> str:
    # libadwaita named colors, shared by GTK apps and Ghostty. Text on accent is crust.
    bg, fg, surface = p.background, p.foreground, p.surface0
    return f"""@define-color window_bg_color {bg};
@define-color window_fg_color {fg};
@define-color view_bg_color {bg};
@define-color view_fg_color {fg};
@define-color headerbar_bg_color {bg};
@define-color headerbar_fg_color {fg};
@define-color headerbar_backdrop_color {bg};
@define-color headerbar_shade_color {surface};
@define-color sidebar_bg_color {bg};
@define-color sidebar_fg_color {fg};
@define-color secondary_sidebar_bg_color {surface};
@define-color dialog_bg_color {bg};
@define-color dialog_fg_color {fg};
@define-color popover_bg_color {surface};
@define-color popover_fg_color {fg};
@define-color card_bg_color {surface};
@define-color card_fg_color {fg};
@define-color accent_bg_color {p.accent};
@define-color accent_fg_color {p.crust};
@define-color accent_color {p.accent};
@define-color destructive_bg_color {p.red};
@define-color shade_color {surface};
"""


def write_ghostty_gtk_css(p: Palette, path: Path) -> None:
    # Ghostty ignores Adw StyleManager on reload-config (#13127); CSS is the live path.
    bg, fg, surface, sel = p.background, p.foreground, p.surface0, p.selection
    content = "/* Generated by asahi-autotheme */\n" + _adwaita_colors(p) + f"""
window, .background {{
  background-color: {bg};
  color: {fg};
}}

headerbar,
.titlebar,
tabbar,
adw-tab-bar,
.adw-tab-bar {{
  background-color: {bg};
  color: {fg};
}}

headerbar button,
tabbar button,
adw-tab-bar button {{
  color: {fg};
}}

adw-dialog,
.dialog-vbox,
window.dialog,
window.popup {{
  background-color: {bg};
  color: {fg};
}}

entry, searchbar, textview {{
  background-color: {surface};
  color: {fg};
  caret-color: {fg};
}}

list, listview, columnview {{
  background-color: {bg};
  color: {fg};
}}

row:selected, .card:selected {{
  background-color: {sel};
  color: {fg};
}}
"""
    _atomic_write(path, content)


def write_ghostty_extra(p: Palette, path: Path, css_name: str = "adaptive.css") -> None:
    content = f"""# Generated by asahi-autotheme
window-theme = ghostty
window-titlebar-background = {p.background}
window-titlebar-foreground = {p.foreground}
gtk-custom-css = ?{css_name}
"""
    _atomic_write(path, content)


def _hyprland_lua(p: Palette) -> str:
    # Borders + groupbar: dofile()d at startup (general.lua) and eval'd live.
    active = _hex_rgb(p.accent)
    secondary = _hex_rgb(p.mauve)
    inactive = _hex_rgb(p.surface1)
    text = _hex_rgb(p.text)
    muted = _hex_rgb(p.subtext0)
    base = _hex_rgb(p.base)
    return f"""hl.config({{
  general = {{
    ["col.active_border"] = {{ colors = {{ "rgb({active})", "rgb({secondary})" }}, angle = 45 }},
    ["col.inactive_border"] = "rgb({inactive})",
  }},
  group = {{
    ["col.border_active"] = {{ colors = {{ "rgb({active})", "rgb({secondary})" }}, angle = 45 }},
    ["col.border_inactive"] = "rgb({inactive})",
    groupbar = {{
      text_color = "rgb({text})",
      text_color_inactive = "rgba({muted}90)",
      col = {{
        active = "rgba({base}dd)",
        inactive = "rgba({base}88)",
      }},
    }},
  }},
}})
"""


def write_hyprland_lua(p: Palette, path: Path) -> None:
    _atomic_write(path, "-- Generated by asahi-autotheme\n" + _hyprland_lua(p))


def write_fade_png(path: Path, rgb: str, height: int, peak: float) -> None:
    """Top-edge fade in `rgb`: alpha `peak` over the first 40% of rows (where the
    text sits), easing to 0 at the last. 4000 wide covers a 3840 panel."""
    r, g, b = (int(rgb[i:i + 2], 16) for i in (0, 2, 4))
    width = 4000
    rows = []
    for y in range(height):
        a = round(255 * peak * min(1.0, (height - y) / (0.6 * height)) ** 2)
        rows.append(b"\x00" + bytes((r, g, b, a)) * width)

    def chunk(kind: bytes, data: bytes) -> bytes:
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data))

    ihdr = struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0)
    png = b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", ihdr) + chunk(b"IDAT", zlib.compress(b"".join(rows), 9)) + chunk(b"IEND", b"")
    _atomic_write(path, png)


def write_hyprlock_conf(p: Palette, path: Path) -> None:
    bg = _hex_rgb(p.background)
    fg = _hex_rgb(p.foreground)
    muted = _hex_rgb(p.subtext0)
    ok = _hex_rgb(p.green)
    fail = _hex_rgb(p.red)
    warn = _hex_rgb(p.yellow)
    teal = _hex_rgb(p.teal)
    content = f"""# Generated by asahi-autotheme
$lock_bg = rgb({bg})
$lock_fg = rgb({fg})
$lock_muted = rgb({muted})
$lock_fail = rgb({fail})
$lock_caps = rgb({warn})
$lock_check = rgba({ok}ee) rgba({teal}ee) 120deg
$lock_ring = rgba({fg}66)
$lock_band = rgba({bg}b8)
"""
    _atomic_write(path, content)
    # Top fade behind the hostname, in the scheme's background.
    write_fade_png(path.parent / "lock-fade-top.png", bg, 260, 0.6)


def write_gtk_css(p: Palette, path: Path) -> None:
    _atomic_write(path, "/* Generated by asahi-autotheme */\n" + _adwaita_colors(p))


def write_firefox_scheme(p: Palette, path: Path) -> None:
    # Message for CaelestiaFox (caelestia scheme.json shape, hex without '#'), streamed by
    # asahi-firefox-theme. Only the M3 roles its browserColours() reads; frame = surfaceDim,
    # toolbar/tabs/popups = surfaceContainer, urlbar = surfaceBright, icons = secondary.
    roles = {
        "surface": p.base,
        "surfaceDim": p.mantle,
        "surfaceContainer": p.base,
        "surfaceContainerHigh": p.surface0,
        "surfaceContainerHighest": p.surface1,
        "surfaceBright": p.surface0,
        "onSurface": p.text,
        "onSurfaceVariant": p.text,
        "outline": p.overlay1,
        "outlineVariant": p.surface1,
        "primary": p.accent,
        "onPrimary": p.crust,
        "secondary": p.text,
        "secondaryContainer": p.surface1,
        "onSecondaryContainer": p.text,
    }
    msg = {
        "name": "asahi",
        "flavour": p.variant,
        "mode": p.mode,
        "variant": p.variant,
        "colours": {k: _hex_rgb(v) for k, v in roles.items()},
    }
    _atomic_write(path, json.dumps(msg, indent=2) + "\n")


